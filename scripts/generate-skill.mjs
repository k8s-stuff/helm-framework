#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  buildValuesContractMarkdown,
  buildMigrationSkillMarkdown,
  buildMigrationPlaybookMarkdown,
} from './generate-migration-skill.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..');

// Deliberate exceptions to the values-contract drift guard (e.g. a
// parent-chart-supplied `global`). Empty today — see
// docs/superpowers/specs/2026-07-29-helm-framework-migration-check-design.md.
const CONTRACT_ALLOWLIST = [];

export function parseVersionArg(argv) {
  const idx = argv.indexOf('--version');
  if (idx === -1 || !argv[idx + 1]) {
    throw new Error('Usage: generate-skill.mjs --version <X.Y.Z>');
  }
  return argv[idx + 1];
}

export function extractChartName(chartYamlContent) {
  const match = chartYamlContent.match(/^name:\s*["']?([^"'\s]+)["']?/m);
  if (!match) {
    throw new Error('Could not find "name:" in Chart.yaml');
  }
  return match[1];
}

export function extractSections(valuesYamlContent) {
  const lines = valuesYamlContent.split('\n');
  const sections = [];
  for (let i = 0; i < lines.length - 2; i++) {
    if (
      /^# =+$/.test(lines[i]) &&
      /^# .+$/.test(lines[i + 1]) &&
      /^# =+$/.test(lines[i + 2])
    ) {
      sections.push(lines[i + 1].replace(/^# /, '').trim());
    }
  }
  return sections;
}

export function extractValuesTable(readmeContent) {
  const marker = '## Values';
  const idx = readmeContent.indexOf(marker);
  if (idx === -1) {
    throw new Error('Could not find "## Values" section in README.md');
  }
  let table = readmeContent.slice(idx);
  // Drop helm-docs' own "Autogenerated from chart metadata..." footer, which
  // starts with a horizontal-rule line — it documents helm-docs, not a value.
  const footerMatch = table.match(/\n-{3,}\n/);
  if (footerMatch) {
    table = table.slice(0, footerMatch.index);
  }
  return table.trim();
}

export function buildSkillMarkdown({ chartName, version, sections }) {
  const sectionList = sections.map((s) => `- ${s}`).join('\n');
  return `---
name: "helm-framework"
description: "Scaffold and configure Helm charts that depend on the ${chartName} library chart. Use when adding ${chartName} as a Helm dependency, writing values.yaml for a chart built on it, or looking up what a value controls."
---

# ${chartName}

## What this skill does

Helps you add \`${chartName}\` (a Helm **library chart**) as a dependency of
your own chart, wire up the single template include it needs, and configure
it correctly through \`values.yaml\`.

Consumers never copy the library's templates — they \`include\` one entry
point and configure everything through their own \`values.yaml\`.

## Quick start

1. Add the dependency to your chart's \`Chart.yaml\`:

\`\`\`yaml
dependencies:
  - name: ${chartName}
    version: "${version}"
    repository: "oci://ghcr.io/k8s-stuff"
\`\`\`

   Or, using the classic Helm repository instead of OCI:

\`\`\`yaml
dependencies:
  - name: ${chartName}
    version: "${version}"
    repository: "https://k8s-stuff.github.io/${chartName}"
\`\`\`

2. Run \`helm dependency update\`.
3. Add one line to a template in your chart (e.g. \`templates/deployment.yaml\`):

\`\`\`yaml
{{ include "${chartName}.deployment.global" . }}
\`\`\`

4. Configure everything through your chart's own \`values.yaml\` — copy in
   only the keys you need from \`resources/values-reference.md\`.

## Values reference

\`resources/values-reference.md\` has the full, generated reference for
every configurable value, grouped into these sections:

${sectionList}

## Worked example

\`resources/example-chart.md\` has a complete, working chart
(\`Chart.yaml\`, \`values.yaml\`, and the single-line template) copied from
this library's own test-template chart.

## Migrating an existing chart?

If you're moving a chart with hand-rolled templates onto \`${chartName}\`
rather than starting fresh, see the sibling \`${chartName}-migration\` skill —
it covers regression checking and orphaned-value cleanup.
`;
}

